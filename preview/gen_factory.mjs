// Writes renderer/factory.js from renderer/preview/preview.wasm: the 40 factory presets as the firmware loads them
// (name, machine, all track parameters, the FM6 voice), and per machine each parameter's label, range and value names.
// Usage: node preview/gen_factory.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const wasm = fs.readFileSync(path.join(here, "../renderer/preview/preview.wasm"));
const { instance } = await WebAssembly.instantiate(wasm, {});
const e = instance.exports;
e._initialize?.();
e.pv_init();
const str = (p) => { const b = new Uint8Array(e.memory.buffer); let s = ""; for (let i = p; b[i]; i++) s += String.fromCharCode(b[i]); return s; };

const NP = e.pv_param_count();
const banks = {}, machines = {};
for (let b = 0; b < 5; b++) {
  const list = [];
  for (let s = 0; s < 8; s++) {
    e.pv_load(b, s);
    const machine = str(e.pv_machine());
    const fm6 = !!e.pv_is_fm6();
    const item = { name: str(e.pv_name(b, s)), machine, p: Array.from({ length: NP }, (_, i) => e.pv_param_get(i)) };
    if (fm6) item.fm6 = Array.from({ length: 158 }, (_, i) => e.pv_fm6_get(i));
    list.push(item);
    if (!machines[machine]) {
      machines[machine] = Array.from({ length: NP }, (_, i) => {
        const d = { label: str(e.pv_param_name(i)), min: e.pv_param_min(i), max: e.pv_param_max(i) };
        if (e.pv_param_enum(i) && d.max - d.min < 64) {
          d.names = [];
          for (let v = d.min; v <= d.max; v++) d.names.push(str(e.pv_param_text(i, v)));
        }
        return d;
      });
    }
  }
  banks["ABCDE"[b]] = list;
}
const globals = Array.from({ length: 6 }, (_, k) => ({ def: e.pv_global_get(k), max: e.pv_global_max(k) }));
const fm6max = Array.from({ length: 158 }, (_, i) => e.pv_fm6_max(i));

const out = `// Generated by preview/gen_factory.mjs from the firmware (preview.wasm). Do not edit by hand.
// FACTORY: banks A..E, 8 presets each: name, machine, p (the ${NP} track parameters in stored order),
//          fm6 (FMSYN only: 155 voice bytes + DRIVE, CUTOFF, OUTPUT).
// MACHINE: per machine, each parameter's label, range and value names as the device shows them.
export const FACTORY = ${JSON.stringify(banks)};
export const MACHINE = ${JSON.stringify(machines)};
export const FX_GLOBAL = ${JSON.stringify(globals)};
export const FM6_MAX = ${JSON.stringify(fm6max)};
`;
fs.writeFileSync(path.join(here, "../renderer/factory.js"), out);
console.log("factory.js:", Object.values(banks).flat().length, "presets,", Object.keys(machines).length, "machines,",
  Object.values(banks).flat().filter((x) => x.fm6).length, "FM6 voices,", out.length, "bytes");
console.log(Object.entries(banks).map(([k, l]) => k + ": " + l.map((x) => `${x.name} [${x.machine}]`).join(", ")).join("\n"));
console.log("8BD labels:", machines["8BD"] && machines["8BD"].map((d, i) => i + ":" + d.label).join(" "));
